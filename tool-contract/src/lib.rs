//! A tool's machine-read contract, described by the tool itself: the JSON
//! Schemas of what it prints and one TypeScript module (types, protocol
//! constants and the reader of its output streams) for the front ends that
//! run it. Each tool's `contracts` feature exports one [`Contract`];
//! `cargo xtask gen` writes every exported contract and names nothing itself.

use anyhow::{Context, Result};
use schemars::JsonSchema;
use serde::Serialize;
use std::collections::HashSet;
use std::path::PathBuf;
use ts_rs::{Config, TS};

const HEADER: &str = "// Generated by `cargo xtask gen` from the tool's Rust output types. Do not edit.\n";

/// One tool's contract.
pub struct Contract {
    /// The TypeScript module's name: an app gets it as `src/generated/<module>.ts`.
    pub module: &'static str,
    /// The binaries an app names in its manifest (`levitate.tools`) to get the module.
    pub binaries: &'static [&'static str],
    /// JSON Schema files: where they go and their text.
    pub schemas: Vec<(PathBuf, String)>,
    /// The module's text (before formatting).
    pub typescript: String,
    cfg: Config,
    declared: HashSet<std::any::TypeId>,
    /// The declarations of the `types_from` call in progress. They are
    /// written sorted, so the module does not depend on the order ts-rs
    /// visits dependencies in (which changes between builds); TypeScript
    /// type aliases may refer to ones declared later.
    pending: Option<Vec<String>>,
}

/// Declares a type after everything it refers to, once.
struct Collect<'c>(&'c mut Contract);

impl ts_rs::TypeVisitor for Collect<'_> {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        self.0.types_from::<T>();
    }
}

impl Contract {
    pub fn new(module: &'static str, binaries: &'static [&'static str]) -> Self {
        Self {
            module,
            binaries,
            schemas: Vec::new(),
            typescript: HEADER.to_string(),
            cfg: Config::new().with_large_int("number"),
            declared: HashSet::new(),
            pending: None,
        }
    }

    /// `T`'s JSON Schema, written to `dir/<name>.schema.json`.
    pub fn schema<T: JsonSchema>(&mut self, dir: impl Into<PathBuf>, name: &str) -> Result<&mut Self> {
        let json = serde_json::to_string_pretty(&schemars::schema_for!(T))?;
        self.schemas.push((dir.into().join(format!("{name}.schema.json")), json + "\n"));
        Ok(self)
    }

    /// `T` and every type it refers to, each once, sorted by name.
    pub fn types_from<T: TS + 'static + ?Sized>(&mut self) -> &mut Self {
        let outermost = self.pending.is_none();
        if outermost {
            self.pending = Some(Vec::new());
        }
        if T::output_path().is_some() && self.declared.insert(std::any::TypeId::of::<T>()) {
            T::visit_dependencies(&mut Collect(self));
            let decl = T::decl(&self.cfg);
            self.pending.as_mut().expect("set above").push(format!("\nexport {decl}\n"));
        }
        if outermost {
            let mut decls = self.pending.take().expect("set above");
            decls.sort();
            for decl in decls {
                self.typescript.push_str(&decl);
            }
        }
        self
    }

    /// `export const NAME = <value as JSON> as const;`, with `doc` as its comment.
    pub fn constant<V: Serialize + ?Sized>(&mut self, name: &str, doc: &str, value: &V) -> Result<&mut Self> {
        let json = serde_json::to_string(value)?;
        let doc = if doc.is_empty() { String::new() } else { format!("/** {doc} */\n") };
        self.typescript.push_str(&format!("\n{doc}export const {name} = {json} as const;\n"));
        Ok(self)
    }

    /// The enum's values as `values`, and, when any value has a doc comment
    /// (its clap help), each value's help as `help`, keyed by its serialized
    /// name (the one `values` lists).
    pub fn value_enum<E: clap::ValueEnum + Serialize>(&mut self, values: &str, help: &str) -> Result<&mut Self> {
        self.constant(values, "", E::value_variants())?;
        let mut docs = serde_json::Map::new();
        for variant in E::value_variants() {
            let value = variant.to_possible_value().context("hidden enum value")?;
            let text = value.get_help().map(|h| h.to_string()).unwrap_or_default();
            let name = serde_json::to_value(variant)?
                .as_str()
                .context("a unit enum variant serializes as a string")?
                .to_string();
            docs.insert(name, text.into());
        }
        if docs.values().any(|text| text.as_str().is_some_and(|t| !t.is_empty())) {
            self.constant(help, "", &docs)?;
        }
        Ok(self)
    }

    /// TypeScript source the tool owns (a reader of its output streams).
    pub fn raw(&mut self, text: &str) -> &mut Self {
        self.typescript.push_str(text);
        self
    }
}
